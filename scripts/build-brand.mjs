#!/usr/bin/env node
// Regenerates every CC-Deskmeter brand asset from one geometry:
//   docs/brand/app-icon.svg          macOS-grid app icon master
//   docs/brand/app-icon-windows.svg  full-bleed master for icon.ico
//   docs/brand/mark.svg              one-color mark
//   docs/brand/tray-template.svg     black mark for the macOS menu bar
//   public/pulse.svg                 favicon
//   src/lib/brand.ts                 mark paths for React and the share card
//   src-tauri/icons/*                bundle icons and the menu-bar icon, via `tauri icon`
//
// Usage: node scripts/build-brand.mjs [--no-icons]
//
// The mark is Claude Code's prompt chevron followed by a heartbeat: the live
// pulse of your sessions. Both are open polylines stroked at one width with
// round caps and joins, so every asset is two plain <path>s: clay on cream.

import { execSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/* Geometry (24×24 box) ---------------------------------------------------- */

/** Prompt chevron: top arm, tip, bottom arm. */
const PROMPT = [[2.3, 6.9], [7.1, 12], [2.3, 17.1]];
/** Heartbeat: lead-in, R peak, S trough, back on the baseline, tail. */
const BEAT = [[10.75, 12], [12.8, 12], [14.6, 5.3], [17.1, 18.7], [18.7, 12], [21.7, 12]];
/** One stroke width for both. */
const STROKE = 2.4;

// A round cap or join reaches STROKE / 2 past its point in every direction, so
// the stroked mark's bounds are the points' bounds grown by that much. Centre
// those bounds in the box.
const xs = [...PROMPT, ...BEAT].map((p) => p[0]);
const ys = [...PROMPT, ...BEAT].map((p) => p[1]);
const shift = [12 - (Math.min(...xs) + Math.max(...xs)) / 2, 12 - (Math.min(...ys) + Math.max(...ys)) / 2];
/** Width of the stroked mark; tiles size the mark by it. */
const MARK_W = Math.max(...xs) - Math.min(...xs) + STROKE;

const num = (v) => String(+v.toFixed(3) || 0);
const polyline = (pts) => pts.map(([x, y], i) => `${i ? "L" : "M"}${num(x + shift[0])} ${num(y + shift[1])}`).join("");
const PROMPT_D = polyline(PROMPT);
const BEAT_D = polyline(BEAT);

/* Artwork ------------------------------------------------------------------ */

const CREAM = "#F3E9D7";
const CLAY = "#D97757";

/** Superellipse |x|^5 + |y|^5 = a^5: the continuous-corner app tile. */
function squircle(c, a, steps = 192) {
  const pts = [];
  for (let i = 0; i < steps; i++) {
    const t = (2 * Math.PI * i) / steps;
    const [co, si] = [Math.cos(t), Math.sin(t)];
    pts.push(`${(c + a * Math.sign(co) * Math.abs(co) ** 0.4).toFixed(1)} ${(c + a * Math.sign(si) * Math.abs(si) ** 0.4).toFixed(1)}`);
  }
  return `M${pts.join("L")}Z`;
}

/** The mark in clay, `width` wide and centred on (c, c). */
function mark(c, width) {
  const s = width / MARK_W;
  return `<g transform="translate(${num(c - 12 * s)} ${num(c - 12 * s)}) scale(${num(s)})" fill="none" stroke="${CLAY}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">
    <path d="${PROMPT_D}"/>
    <path d="${BEAT_D}"/>
  </g>`;
}

function appIcon({ note, half, markWidth, shadow }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!--
    CC-Deskmeter app icon. ${note}
    Claude Code's prompt chevron followed by a heartbeat: the live pulse of
    your sessions.
    Generated by scripts/build-brand.mjs; edit the geometry there.
  -->
  <defs>
    <path id="tile" d="${squircle(512, half)}"/>${
      shadow
        ? `
    <filter id="drop" x="-10%" y="-10%" width="120%" height="125%"><feGaussianBlur stdDeviation="14"/></filter>`
        : ""
    }
  </defs>${
    shadow
      ? `
  <use href="#tile" transform="translate(0 12)" fill="#3D2A1E" opacity=".3" filter="url(#drop)"/>`
      : ""
  }
  <use href="#tile" fill="${CREAM}"/>
  ${mark(512, 2 * half * markWidth)}
</svg>
`;
}

const FILES = {
  "docs/brand/app-icon.svg": appIcon({
    note: "Master for the bundle icons (macOS grid: 824 px tile,\n    100 px margin).",
    half: 412,
    markWidth: 0.64,
    shadow: true,
  }),
  "docs/brand/app-icon-windows.svg": appIcon({
    note: "Full-bleed variant for icon.ico, so the\n    16-32 px taskbar and title-bar sizes are not shrunk by the macOS margin.",
    half: 496,
    markWidth: 0.7,
    shadow: false,
  }),
  "docs/brand/mark.svg": `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="${CLAY}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">
  <!-- CC-Deskmeter mark in one color: a prompt chevron and a heartbeat. -->
  <path d="${PROMPT_D}"/>
  <path d="${BEAT_D}"/>
</svg>
`,
  // A template image: macOS keeps only its alpha and tints it to match the menu bar.
  "docs/brand/tray-template.svg": `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">
  <!-- CC-Deskmeter menu-bar icon (macOS template image). -->
  <path d="${PROMPT_D}"/>
  <path d="${BEAT_D}"/>
</svg>
`,
  "public/pulse.svg": `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <rect width="32" height="32" rx="7.5" fill="${CREAM}"/>
  ${mark(16, 32 * 0.74)}
</svg>
`,
  "src/lib/brand.ts": `/*
 * The CC-Deskmeter mark: Claude Code's prompt chevron followed by a heartbeat,
 * the live pulse of your sessions. Two open paths in a 24×24 box, stroked at
 * MARK_STROKE with round caps and joins.
 * Generated by scripts/build-brand.mjs, which also writes the app icons.
 */
export const MARK_PROMPT = "${PROMPT_D}";
export const MARK_BEAT = "${BEAT_D}";
/** Stroke width of both paths, in the 24×24 box. */
export const MARK_STROKE = ${STROKE};
`,
};

for (const [rel, content] of Object.entries(FILES)) {
  mkdirSync(dirname(join(ROOT, rel)), { recursive: true });
  writeFileSync(join(ROOT, rel), content);
  console.log(`wrote ${rel}`);
}

/* Bundle icons ------------------------------------------------------------- */

if (!process.argv.includes("--no-icons")) {
  const icons = join(ROOT, "src-tauri", "icons");
  /** Embedded by `src-tauri/src/tray.rs`; not a bundle icon. */
  const TRAY_ICON = "tray-template.png";
  const tmp = mkdtempSync(join(tmpdir(), "cc-deskmeter-icons-"));
  const render = (svg, out, args = "") =>
    execSync(`npx tauri icon "${join(ROOT, "docs", "brand", svg)}" -o "${out}" ${args}`, { cwd: ROOT, stdio: "ignore" });
  try {
    render("app-icon.svg", join(tmp, "mac"));
    render("app-icon-windows.svg", join(tmp, "win"));
    // macOS draws menu-bar icons 18 pt tall: 36 px covers Retina screens.
    render("tray-template.svg", join(tmp, "tray"), "--png 36");
    // Refresh the files the bundle already ships; skip the Android/iOS sets.
    for (const name of readdirSync(icons)) {
      if (name === TRAY_ICON) continue;
      copyFileSync(join(tmp, name === "icon.ico" ? "win" : "mac", name), join(icons, name));
      console.log(`wrote src-tauri/icons/${name}`);
    }
    copyFileSync(join(tmp, "tray", "36x36.png"), join(icons, TRAY_ICON));
    console.log(`wrote src-tauri/icons/${TRAY_ICON}`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
